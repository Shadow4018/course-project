/**
 * @interface IManagable
 * @brief Абстрактний інтерфейс для керування об'єктами системи.
 * @details
 * Інтерфейс `IManagable` визначає базовий набір методів,
 * які повинні бути реалізовані будь-яким класом, що підтримує
 * операції керування даними, наприклад: додавання, редагування, видалення, пошук тощо.
 *
 * Використовується як базовий клас для:
 * - @ref FlightManager — керування рейсами;
 * - @ref UserManager — керування користувачами.
 */
class IManagable
{
public:
	/**
	 * @brief Віртуальний деструктор.
	 * @details Забезпечує коректне звільнення ресурсів у похідних класах.
	 */
	virtual ~IManagable() = default;

	/// ========================= MAIN FUNCTIONALITY ========================= ///
	/**
	 * @brief Додає новий об'єкт.
	 * @details Реалізується у похідних класах для створення нового запису (рейсу, користувача тощо).
	 */
	virtual void add() = 0;

	/**
	 * @brief Редагує існуючий об'єкт.
	 * @details Використовується для зміни даних наявного запису.
	 */
	virtual void edit() = 0;

	/**
	 * @brief Видаляє об'єкт.
	 * @details Реалізується для видалення записів із колекції або файлу.
	 */
	virtual void remove() = 0;

	/**
	 * @brief Виконує пошук об'єктів.
	 * @details Дає змогу знаходити об'єкти за одним критерієм (наприклад, номером рейсу або іменем користувача).
	 */
	virtual void search() = 0;

	/**
	 * @brief Сортує об'єкти за визначеним параметром.
	 * @details Використовується для впорядкування даних (наприклад, за іменем, датою чи номером).
	 */
	virtual void sortData() = 0;

	/**
	 * @brief Фільтрує об'єкти за кількома умовами.
	 * @details Дозволяє обмежити вивід лише тими елементами, що відповідають зазначеним критеріям.
	 */
	virtual void filter() = 0;
};

